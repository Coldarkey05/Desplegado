import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
test('V5: login, selección, usuarios unificados y privilegios por roles', async ({page,request})=>{
 const base=process.env.BACKEND_URL!, suffix=String(Date.now()).slice(-6), password='Browser-'+randomUUID();
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/login');
 await page.getByLabel('Nombre de usuario',{exact:true}).fill('admin');
 await page.getByLabel('Contraseña',{exact:true}).fill(process.env.TEST_ADMIN_PASSWORD!);
 await page.getByRole('button',{name:'Ingresar al sistema'}).click();
 await expect(page.getByRole('heading',{name:'Selecciona tu rol'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Entrar como Admin',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Entrar como Operador',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Entrar como Admin',exact:true}).click();
 await page.getByRole('link',{name:'Usuarios',exact:true}).click();
 await expect(page.getByRole('link',{name:'Credenciales',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Nuevo usuario',exact:true}).click();
 const form=page.getByRole('dialog');
 await form.getByLabel('DNI',{exact:false}).fill('8'+suffix+'0');
 await form.getByLabel('Nombres',{exact:false}).fill('Usuario');
 await form.getByLabel('Apellidos',{exact:false}).fill('Multirrol');
 await form.getByLabel('Nombre de usuario',{exact:false}).fill('browser-'+suffix);
 await form.getByLabel('Contraseña',{exact:false}).fill(password);
 await form.getByRole('button',{name:'Crear registro',exact:true}).click();
 await expect(form).toHaveCount(0);
 await expect(page.getByRole('cell',{name:'browser-'+suffix,exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Asignar roles',exact:true}).click();
 await page.getByLabel('Usuario para asignar roles').selectOption({label:'Usuario Multirrol · browser-'+suffix});
 await page.getByLabel('Asignar rol Administrador',{exact:true}).check();
 await page.getByLabel('Asignar rol Operador',{exact:true}).check();
 await page.getByLabel('Asignar rol Orientador',{exact:true}).check();
 await page.getByLabel('Asignar rol Usuario',{exact:true}).uncheck();
 await page.getByRole('button',{name:'Guardar roles'}).click();
 await expect(page.getByRole('button',{name:'Guardar roles'})).toBeDisabled();
 await page.screenshot({path:'test-results/roles-privilegios-v5.png',fullPage:true});
 await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click();
 await page.getByLabel('Nombre de usuario',{exact:true}).fill('browser-'+suffix);
 await page.getByLabel('Contraseña',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Ingresar al sistema'}).click();
 for(const r of ['Admin','Operador','Orientador'])await expect(page.getByRole('button',{name:'Entrar como '+r,exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/selector-roles-v5.png',fullPage:true});
 await page.getByRole('button',{name:'Entrar como Operador',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Mi ventanilla',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Usuarios',exact:true})).toHaveCount(0);
 await page.goto('/admin/usuarios');
 await expect(page.getByRole('heading',{name:'Mi ventanilla',exact:true})).toBeVisible();
 const token=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('sat.session')!).token);
 expect((await request.get(base+'/admin/usuarios',{headers:{Authorization:'Bearer '+token}})).status()).toBe(403);
 await page.getByRole('button',{name:'Cambiar rol'}).click();
 await page.getByRole('button',{name:'Entrar como Admin',exact:true}).click();
 await page.getByRole('link',{name:'Usuarios',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Usuarios',exact:true})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Usuarios',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Cambiar rol'}).click();
 await page.getByRole('button',{name:'Entrar como Orientador',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Tickets y preferencias',exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Cambiar rol'}).click();
 await expect(page.getByRole('button',{name:'Entrar como Operador',exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/selector-movil-v5.png',fullPage:true});
 expect(errors).toEqual([]);
});

test('V4.1: módulo reservado visible y deshabilitado al crear usuario',async({page,request})=>{
 const suffix=String(Date.now()).slice(-6),base=process.env.BACKEND_URL!;
 const login=await request.post(base+'/auth/login',{data:{nombre_usuario:'admin',password:process.env.TEST_ADMIN_PASSWORD!}});
 const boot=await login.json();
 const selection=await request.post(base+'/auth/seleccionar-rol',{headers:{Authorization:'Bearer '+boot.access_token},data:{rol:'Admin'}});
 const headers={Authorization:'Bearer '+(await selection.json()).access_token};
 const module=await request.post(base+'/admin/modulos',{headers,data:{numero_modulo:'Reserva '+suffix,estado:'Cerrado'}});
 expect(module.ok()).toBeTruthy();const m=await module.json();
 const user=await request.post(base+'/admin/usuarios',{headers,data:{dni:'7'+suffix+'0',nombres:'Reserva',apellidos:'Browser',nombre_usuario:'reserva-ui-'+suffix,password:'Browser-'+randomUUID(),rol_sistema:'Operador',id_modulo_asignado:m.id_modulo}});
 expect(user.ok()).toBeTruthy();
 await page.goto('/login');
 await page.getByLabel('Nombre de usuario',{exact:true}).fill('admin');
 await page.getByLabel('Contraseña',{exact:true}).fill(process.env.TEST_ADMIN_PASSWORD!);
 await page.getByRole('button',{name:'Ingresar al sistema'}).click();
 await page.getByRole('button',{name:'Entrar como Admin',exact:true}).click();
 await page.getByRole('link',{name:'Usuarios',exact:true}).click();
 await page.getByRole('button',{name:'Nuevo usuario',exact:true}).click();
 await expect(page.getByLabel('Cargo del trabajador')).toHaveCount(0);
 const option=page.getByLabel('Módulo asignado',{exact:false}).locator('option[value="'+m.id_modulo+'"]');
 await expect(option).toHaveText('Reserva '+suffix+' — No disponible');
 await expect(option).toHaveJSProperty('disabled',true);
 await page.screenshot({path:'test-results/modulos-disponibilidad-v41.png',fullPage:true});
});
