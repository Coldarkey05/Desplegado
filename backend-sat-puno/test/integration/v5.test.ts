import {test} from 'node:test';import assert from 'node:assert/strict';import {randomUUID} from 'node:crypto';
const base=(process.env.TEST_API_URL??'http://127.0.0.1:3100')+'/api';
test('V5: roles dinámicos, permisos mixtos, edición de módulo y revocación',async()=>{
 const suffix=String(Date.now()).slice(-6),password='V5-test-'+randomUUID();
 async function call(path:string,method='GET',body?:unknown,token?:string,status=200){const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body!==undefined?{body:JSON.stringify(body)}:{})});const d=await r.json();assert.equal(r.status,status,JSON.stringify(d));return d;}
 async function login(name:string,pw:string,role:string){const r=await call('/auth/login','POST',{nombre_usuario:name,password:pw},undefined,201);return (await call('/auth/seleccionar-rol','POST',{rol:role},r.access_token,201)).access_token;}
 const admin=await login('admin',process.env.ADMIN_PASSWORD!,'Admin');
 const perms=['tickets.emitir','pantalla.ver','ventanilla.atender','ventanilla.asignacion','servicios.ver','servicios.gestionar','cola.ver'];
 const role=await call('/admin/roles','POST',{codigo:'Mixto'+suffix,nombre:'Rol mixto '+suffix,permisos:perms},admin,201);
 const grants=await call('/admin/privilegios','GET',undefined,admin);
 assert.equal(grants.roles_detalle.find((r:any)=>r.codigo===role.codigo).nombre,role.nombre);
 const svc=await call('/admin/servicios','POST',{nombre_servicio:'Mixto '+suffix},admin,201);
 const m1=await call('/admin/modulos','POST',{numero_modulo:'M1-'+suffix,id_servicio_principal:svc.id_servicio},admin,201);
 const m2=await call('/admin/modulos','POST',{numero_modulo:'M2-'+suffix,id_servicio_principal:svc.id_servicio},admin,201);
 const user=await call('/admin/usuarios','POST',{dni:'9'+suffix+'0',nombres:'Mixto',apellidos:'Pruebas',nombre_usuario:'mixto'+suffix,password,rol_sistema:role.codigo,id_modulo_asignado:m1.id_modulo},admin,201);
 await call('/admin/usuarios/'+user.id_usuario,'PATCH',{id_modulo_asignado:m2.id_modulo},admin);
 assert.equal((await call('/admin/usuarios/'+user.id_usuario,'GET',undefined,admin)).id_modulo_asignado,m2.id_modulo);
 let op=await login(user.nombre_usuario,password,role.codigo);
 await call('/admin/servicios','POST',{nombre_servicio:'Permitido '+suffix},op,201);
 await call('/admin/usuarios','GET',undefined,op,403);
 await call('/admin/roles','POST',{codigo:'Escalado'+suffix,nombre:'Escalado',permisos:['usuarios.eliminar']},op,403);
 await call('/admin/modulos/'+m2.id_modulo+'/modo','PATCH',{atencion_automatica:false},op,403);
 await call('/admin/modulos/2147483647/modo','PATCH',{atencion_automatica:false},admin,404);
 await call('/admin/modulos/'+m2.id_modulo+'/modo','PATCH',{atencion_automatica:'false'},admin,400);
 await call('/admin/modulos/'+m2.id_modulo+'/modo','PATCH',{atencion_automatica:false},admin);
 assert.equal((await call('/ventanilla','GET',undefined,op)).modulo.atencion_automatica,false);
 const t=await call('/turnos','POST',{dni:'7'+suffix+'0',id_servicio:svc.id_servicio,solicitud_id:randomUUID()},op,201);
 await call('/ventanilla/modo','PATCH',{atencion_automatica:false},op);
 await call('/ventanilla/abrir','POST',{},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual,null);
 await call('/admin/cola/reanudar','POST',{},admin,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual,null);
 const attempts=await Promise.all([1,2].map(()=>fetch(base+'/ventanilla/llamar-siguiente',{method:'POST',headers:{Authorization:'Bearer '+op,'Content-Type':'application/json'},body:'{}'})));
 assert.deepEqual(attempts.map(r=>r.status).sort(),[201,409]);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual.estado,'LLAMADO');
 await call('/turnos/'+t.id_turno+'/iniciar','POST',{},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual.id_turno,t.id_turno);
 await call('/admin/usuarios/'+user.id_usuario,'PATCH',{id_modulo_asignado:m1.id_modulo},admin,409);
 await call('/admin/roles/'+role.id_rol,'PATCH',{nombre:role.nombre,permisos:['tickets.emitir']},admin,409);
 await call('/admin/roles/'+role.id_rol,'PATCH',{nombre:role.nombre,permisos:perms,activo:false},admin,409);
 await call('/turnos/'+t.id_turno+'/finalizar','POST',{},op,201);
 assert.equal((await call('/pantalla','GET',undefined,op)).actuales.some((x:any)=>x.id_turno===t.id_turno),false);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual,null);
 await call('/ventanilla/llamar-siguiente','POST',{},op,409);
 const next=await call('/turnos','POST',{dni:'7'+suffix+'2',id_servicio:svc.id_servicio,solicitud_id:randomUUID()},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual,null);
 await call('/admin/modulos/'+m2.id_modulo+'/modo','PATCH',{atencion_automatica:true},admin);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual.id_turno,next.id_turno);
 await call('/admin/modulos/'+m2.id_modulo+'/modo','PATCH',{atencion_automatica:false},admin);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual.id_turno,next.id_turno);
 const third=await call('/turnos','POST',{dni:'7'+suffix+'3',id_servicio:svc.id_servicio,solicitud_id:randomUUID()},op,201);
 await call('/turnos/'+next.id_turno+'/finalizar','POST',{},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual,null);
 await call('/ventanilla/cerrar','POST',{},op,201);
 await call('/ventanilla/llamar-siguiente','POST',{},op,409);
 await call('/ventanilla/abrir','POST',{},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).modulo.atencion_automatica,false);
 await call('/ventanilla/llamar-siguiente','POST',{},op,201);
 await call('/turnos/'+third.id_turno+'/iniciar','POST',{},op,201);
 await call('/turnos/'+third.id_turno+'/finalizar','POST',{},op,201);
 await call('/ventanilla/finalizar-jornada','POST',{},op,201);
 await call('/admin/roles/'+role.id_rol,'PATCH',{nombre:role.nombre,permisos:['tickets.emitir'],activo:true},admin);
 await call('/auth/me','GET',undefined,op,401);
 op=await login(user.nombre_usuario,password,role.codigo);
 await call('/ventanilla','GET',undefined,op,403);
 await call('/ventanilla/modo','PATCH',{atencion_automatica:false},op,403);
 await call('/ventanilla/llamar-siguiente','POST',{},op,403);
 await call('/admin/servicios','GET',undefined,op,403);
 await call('/admin/roles/'+role.id_rol,'DELETE',undefined,admin,409);
 await call('/admin/roles/'+role.id_rol,'PATCH',{nombre:role.nombre,permisos:['tickets.emitir'],activo:false},admin);
 await call('/auth/me','GET',undefined,op,401);
 const before=await call('/auth/login','POST',{nombre_usuario:user.nombre_usuario,password},undefined,201);
 assert.equal(before.usuario.roles.includes(role.codigo),false);
 await call('/auth/seleccionar-rol','POST',{rol:role.codigo},before.access_token,403);
 const roles=await call('/admin/roles','GET',undefined,admin);
 assert(roles.roles.some((r:any)=>r.codigo==='Supervisor'));
 await call('/admin/roles/'+roles.roles.find((r:any)=>r.codigo==='Admin').id_rol,'PATCH',{nombre:'Admin',permisos:[]},admin,403);
 const disposable=await call('/admin/roles','POST',{codigo:'Temporal'+suffix,nombre:'Temporal',permisos:[]},admin,201);
 await call('/admin/roles/'+disposable.id_rol,'DELETE',undefined,admin);
});
