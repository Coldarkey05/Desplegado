import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
const base=(process.env.TEST_API_URL ?? 'http://127.0.0.1:3100')+'/api';
test('V5 regresión: identidad única, selección de rol, jerarquía, revocación y cola completa', async()=>{
 const suffix=String(Date.now()).slice(-6), password='V4-test-'+randomUUID();
 async function call(path:string,method='GET',body?:unknown,token?:string,expected=200){
  const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body!==undefined?{body:JSON.stringify(body)}:{})});
  const data=await r.json(); assert.equal(r.status,expected,JSON.stringify(data));return data;
 }
 async function login(name:string,pw:string){return call('/auth/login','POST',{nombre_usuario:name,password:pw},undefined,201)}
 async function role(token:string,rol:string){return (await call('/auth/seleccionar-rol','POST',{rol},token,201)).access_token;}
 const boot=await login('admin',process.env.ADMIN_PASSWORD!);
 assert.equal(boot.usuario.rol_sistema,'Seleccion');assert.deepEqual(boot.usuario.permisos,[]);
 await call('/admin/usuarios','GET',undefined,boot.access_token,403);
 await call('/auth/seleccionar-rol','POST',{rol:'Operador'},boot.access_token,403);
 const admin=await role(boot.access_token,'Admin');
 const create=async(n:number)=>call('/admin/usuarios','POST',{dni:String(n)+suffix+'0',nombres:'Persona',apellidos:'V4 '+n,nombre_usuario:'v4-'+n+suffix,password},admin,201);
 const person=await create(1), second=await create(2);
 assert.equal(person.contrasena_hash,undefined);assert.equal(person.version_token,undefined);
 await call('/admin/usuarios/'+person.id_usuario,'PATCH',{rol_sistema:'Admin'},admin,400);
 await call('/admin/credenciales_sistema','GET',undefined,admin,403);
 await call('/admin/privilegios/'+person.id_usuario,'PATCH',{roles:['Admin','Operador','Orientador']},admin);
 await call('/admin/privilegios/'+second.id_usuario,'PATCH',{roles:['Operador']},admin);
 let account=await login(person.nombre_usuario,password);
 assert.equal(account.usuario.roles.length,3);
 const op=await role(account.access_token,'Operador'), lower=await role(account.access_token,'Admin');
 await call('/admin/servicios','POST',{nombre_servicio:'Prohibido'},op,403);
 await call('/admin/usuarios/'+boot.usuario.id_usuario,'DELETE',undefined,lower,403);
 await call('/admin/privilegios/'+boot.usuario.id_usuario,'PATCH',{roles:['Usuario']},lower,403);
 await call('/admin/usuarios/'+person.id_usuario,'PATCH',{nombres:'Yo'},lower,403);
 await call('/admin/privilegios/'+person.id_usuario,'PATCH',{roles:['Admin','Admin']},admin,400);
 const service=await call('/admin/servicios','POST',{nombre_servicio:'Servicio V4 '+suffix},admin,201);
 const pref=await call('/admin/tipospreferencia','POST',{nombre_tipo:'Preferente V4 '+suffix,prioridad:10},admin,201);
 const modules=[];
 for(let i=0;i<2;i++)modules.push(await call('/admin/modulos','POST',{numero_modulo:'V4-'+i+suffix,id_servicio_principal:service.id_servicio,estado:'Cerrado'},admin,201));
 const op2=await role((await login(second.nombre_usuario,password)).access_token,'Operador');
 await call('/ventanilla/asignacion','PATCH',{id_modulo:modules[0].id_modulo,id_servicio:service.id_servicio},op);
 await call('/ventanilla/asignacion','PATCH',{id_modulo:modules[1].id_modulo,id_servicio:service.id_servicio},op2);
 await call('/auth/seleccionar-rol','POST',{rol:'Admin'},op,201);
 await call('/admin/privilegios/'+person.id_usuario,'PATCH',{roles:['Orientador']},admin,409);
 const ordinary=await call('/turnos','POST',{dni:'3'+suffix+'0',id_servicio:service.id_servicio,solicitud_id:randomUUID()},admin,201);
 await call('/auth/seleccionar-rol','POST',{rol:'Orientador'},account.access_token,403);
 await call('/orientacion/contribuyente/'+'4'+suffix+'0','PATCH',{nombres:'Preferente',apellidos:'V4',id_tipo_preferencia:pref.id_tipo_preferencia},admin);
 const priority=await call('/turnos','POST',{dni:'4'+suffix+'0',id_servicio:service.id_servicio,solicitud_id:randomUUID()},admin,201);
 await call('/ventanilla/abrir','POST',{},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op)).turno_actual.id_turno,priority.id_turno);
 await call('/ventanilla/abrir','POST',{},op2,201);
 assert.equal((await call('/ventanilla','GET',undefined,op2)).turno_actual.id_turno,ordinary.id_turno);
 await call('/turnos/'+ordinary.id_turno+'/finalizar','POST',{},op,403);
 await call('/turnos/'+ordinary.id_turno+'/finalizar','POST',{},op2,201);
 await call('/turnos/'+priority.id_turno+'/derivar','POST',{id_servicio_destino:service.id_servicio,motivo:'Otro operador del mismo servicio'},op,201);
 assert.equal((await call('/ventanilla','GET',undefined,op2)).turno_actual.id_turno,priority.id_turno);
 await call('/turnos/'+priority.id_turno+'/finalizar','POST',{},op2,201);
 assert.equal((await call('/pantalla','GET',undefined,admin)).actuales.length,0);
 await call('/ventanilla/finalizar-jornada','POST',{},op,201);
 await call('/ventanilla/finalizar-jornada','POST',{},op2,201);
 await role(op,'Admin');
 const before=await role(account.access_token,'Orientador');
 await call('/admin/servicios','GET',undefined,before,200);
 await call('/admin/privilegios/'+person.id_usuario,'PATCH',{roles:['Operador','Usuario']},admin);
 await call('/admin/usuarios','GET',undefined,lower,401);
 await call('/auth/me','GET',undefined,op,401);
 account=await login(person.nombre_usuario,password);
 await call('/auth/seleccionar-rol','POST',{rol:'Admin'},account.access_token,403);
 assert.equal((await call('/admin/usuarios/'+person.id_usuario,'GET',undefined,admin)).nivel_admin,1);
 await call('/admin/usuarios/'+second.id_usuario,'PATCH',{activo:false},admin);
 await call('/auth/me','GET',undefined,op2,401);
 await call('/auth/login','POST',{nombre_usuario:second.nombre_usuario,password},undefined,401);
 await call('/admin/usuarios/'+second.id_usuario,'PATCH',{activo:true,password:'Changed-'+password},admin);
 await call('/auth/login','POST',{nombre_usuario:second.nombre_usuario,password},undefined,401);
 const relog=await login(second.nombre_usuario,'Changed-'+password);
 await call('/auth/logout','POST',{},relog.access_token,201);
 await call('/auth/me','GET',undefined,relog.access_token,401);

 // V4.1: eliminación de cargo y reserva administrativa concurrente.
 assert.equal(Object.hasOwn(person,'rol'),false);
 await call('/admin/usuarios/'+person.id_usuario,'PATCH',{rol:'Operador'},admin,400);
 const targetModule=modules[0].id_modulo;
 const payload=(n:number)=>({dni:String(n)+suffix+'0',nombres:'Reserva',apellidos:'V41',nombre_usuario:'reserva-'+n+suffix,password,rol_sistema:'Operador',id_modulo_asignado:targetModule});
 const answers=await Promise.all([5,6].map(n=>fetch(base+'/admin/usuarios',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+admin},body:JSON.stringify(payload(n))})));
 assert.deepEqual(answers.map(r=>r.status).sort(),[201,409]);
 const winning=await answers.find(r=>r.status===201)!.json();
 let options=await call('/opciones/modulos','GET',undefined,admin);
 assert.equal(options.find((m:any)=>m.id_modulo===targetModule).disponible_para_asignar,false);
 const selected=await role((await login(winning.nombre_usuario,password)).access_token,'Operador');
 await call('/ventanilla/finalizar-jornada','POST',{},selected,201);
 options=await call('/opciones/modulos','GET',undefined,admin);
 assert.equal(options.find((m:any)=>m.id_modulo===targetModule).disponible_para_asignar,true);
 await call('/admin/usuarios','POST',{...payload(7),rol_sistema:'Usuario'},admin,400);
 await call('/admin/usuarios','POST',{...payload(7),activo:false},admin,400);
 await call('/admin/usuarios','POST',{...payload(7),id_modulo_asignado:2147483647},admin,404);
});
